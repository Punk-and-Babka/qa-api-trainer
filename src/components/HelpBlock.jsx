import { useState } from 'react';
import { MODES, isToolEnabled } from '../modes.js';

// Текст справки «как этим пользоваться». Сворачиванием самого раздела
// управляет Section, здесь только содержимое.
//
// Справка разделена на две части. Первая отвечает на три вопроса, без которых
// нельзя сделать первый шаг: что это такое, что требуется сделать, в каком
// порядке работать. Вторая — всё остальное — убрана под «Подробнее».
//
// Причина в том, что до правки справка занимала больше пятисот слов и лежала
// первым же блоком на экране: человек, открывший тренажёр впервые, упирался в
// простыню текста раньше, чем видел хоть один запрос. Прочитать её целиком
// полезно, но не до первого запроса, а после.
//
// Раскрытие живёт в useState и не сохраняется — по той же причине, по которой
// не сохраняется открытость справки по разделам: это сиюминутный взгляд в
// шпаргалку, а не выбранная раскладка.
//
// Шаги про инструменты показываются по режиму: обещать в справке кнопку,
// которой сейчас нет на экране, — верный способ запутать.

export default function HelpBlock({ mode }) {
  const [more, setMore] = useState(false);

  const schema = isToolEnabled(mode, 'schema');
  const tests = isToolEnabled(mode, 'tests');
  const variables = isToolEnabled(mode, 'variables');

  return (
    <div className="help">
      <h4 className="help__heading">Что это такое</h4>
      <p>
        Тренажёр для тестирования REST API. Слева — <b>эталонная
        спецификация</b>: описание того, как API обязан себя вести. В середине —
        клиент запросов, как Postman. Справа — ответ сервера.
      </p>
      <p>
        Сервер здесь <b>поддельный и работает прямо в этой вкладке</b>: никакой
        сети нет, запросы никуда не уходят. И в нём <b>намеренно оставлено
        десять дефектов</b> — мест, где поведение расходится со спецификацией.
        Их и нужно найти, а каждое расхождение описать баг-репортом: эндпоинт,
        тип дефекта, описание своими словами. Счётчик найденного — в шапке.
      </p>

      <h4 className="help__heading">Порядок работы</h4>
      <ol className="help__steps">
        <li>
          Возьми задание из списка ниже и собери запрос в средней колонке. Путь
          пишется целиком: <code>/users?limit=0</code>.
        </li>
        <li>
          Сравни ответ справа со спецификацией: статус, набор полей, формат
          значений.
        </li>
        {schema ? (
          <li>
            <b>Проверить по схеме</b> — сверяет тело ответа с моделью из
            спецификации автоматически. Не заменяет глаза: часть дефектов она
            не видит.
          </li>
        ) : null}
        {tests ? (
          <li>
            <b>Tests</b> — настоящий JavaScript. <code>pm.test(имя, fn)</code>,
            внутри <code>pm.expect(…)</code>. Тест падает, если функция бросила
            исключение. Прогоняются сами после каждого ответа.
          </li>
        ) : null}
        {variables ? (
          <li>
            <b>Переменные</b> нужны для цепочек: сохрани значение из ответа
            через <code>pm.environment.set('userId', …)</code> и подставь в
            следующий запрос как <code>{'{{userId}}'}</code>. Так видно, когда
            ответ одного запроса противоречит ответу другого.
          </li>
        ) : null}
        <li>
          Нашёл расхождение — заведи <b>баг-репорт</b>: форма появится справа
          после первого же ответа.
        </li>
      </ol>

      <button
        className="btn btn--small help__more"
        type="button"
        aria-expanded={more}
        onClick={() => setMore((current) => !current)}
      >
        {more ? 'Свернуть подробности' : 'Подробнее'}
      </button>

      {more ? (
        <div className="help__extra">
          <h4 className="help__heading">Чем это отличается от Postman</h4>
          <p>
            В Postman нет правильного ответа: увидел странность — сам решаешь,
            баг это или так задумано, и спорить об этом идёшь к аналитику. Здесь
            правильный ответ известен заранее. Спецификация — эталон, дефекты
            описаны списком, поэтому тренажёр может сказать, нашёл ли ты
            настоящее расхождение или ложную тревогу. Ради этого он и сделан;
            интерфейс намеренно минимальный, копировать Postman смысла нет.
          </p>

          <h4 className="help__heading">Какие бывают дефекты</h4>
          <p>
            Разные по характеру: часть видна в одном ответе, часть — только если
            сравнить два ответа между собой, часть — только на границах
            допустимых значений. Ни один не находится случайным тыканьем: под
            каждым лежит проверка, которую надо придумать.
          </p>

          <h4 className="help__heading">Режимы</h4>
          <p>
            Переключатель в шапке решает, сколько инструментов на экране.{' '}
            {MODES.map((item) => item.label).join(' → ')} — это лестница: каждый
            следующий добавляет к предыдущему. Смысл в том, чтобы пройти
            сценарий сначала руками, потом с проверкой контракта, потом с
            тестами и увидеть разницу в трудозатратах на себе.
          </p>
          <p>
            Ни один режим не делает задание нерешаемым: все дефекты находятся
            глазами, инструменты только ускоряют поиск. Найденное при
            переключении не теряется — счётчик и репорты общие.
          </p>

          <h4 className="help__heading">Что происходит с данными</h4>
          <p>
            Запросы <code>POST</code>, <code>PUT</code> и <code>DELETE</code>{' '}
            по-настоящему меняют данные сервера: созданный пользователь появится
            в списке, удалённый исчезнет. Кнопка «Сбросить состояние сервера»
            возвращает данные к исходным и ничего больше не трогает. Перезагрузка
            страницы тоже сбрасывает сервер, но твой прогресс, тестовый скрипт и
            переменные сохраняются. «Начать заново» стирает и их.
          </p>

          <h4 className="help__heading">Чему тут можно научиться</h4>
          <p>
            Читать спецификацию как источник ожидаемого результата, а не как
            документацию. Проверять контракт ответа по JSON Schema и понимать,
            чего такая проверка принципиально не видит. Писать автотесты в том
            же виде, в каком они пишутся в Postman. Строить цепочки запросов и
            ловить дефекты, которые в одном ответе не видны. Точно
            формулировать, что именно расходится с ожиданием.
          </p>

          <p className="help__note">
            У каждого раздела в заголовке есть кнопка «?» — там справка по этому
            разделу: списки методов, матчеров и ключевых слов. Сам заголовок
            сворачивает раздел.
          </p>
        </div>
      ) : null}
    </div>
  );
}
