// Инвариант тот же, что у Users: задание не может ссылаться на
// несуществующий дефект или на неизвестный инструмент.
function assertTasksReferKnownBugs(tasks, catalog) {
  for (const task of tasks) {
    for (const tool of task.tools) {
      if (!Object.hasOwn(TASK_TOOLS, tool)) {
        throw new Error(`Задание ${task.id} ссылается на неизвестный инструмент "${tool}".`);
      }
    }
    for (const bugId of task.bugIds) {
      if (!catalog.some((bug) => bug.id === bugId)) {
        throw new Error(
          `Задание ${task.id} ссылается на дефект ${bugId}, которого нет в каталоге Orders.`,
        );
      }
    }
  }
}

assertTasksReferKnownBugs(ordersTasks, bugs);
