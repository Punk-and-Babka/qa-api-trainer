// Тот же инвариант, что и в Users: пара «эндпоинт + тип» обязана быть
// уникальной, иначе сверка баг-репорта опознает не тот дефект. Проверка
// повторена здесь, а не вынесена в общий модуль, сознательно: каталог должен
// падать при импорте самого себя, не завися от того, кто его подключил.
function assertUniquePairs(list) {
  const seen = new Map();

  for (const bug of list) {
    for (const type of bug.types) {
      const key = `${bug.endpoint} + ${type}`;
      const previous = seen.get(key);

      if (previous !== undefined) {
        throw new Error(
          `Каталог Orders: дубль пары "${key}" — ${previous} и ${bug.id}. ` +
            'Сверка опознаёт дефект по этой паре, она обязана быть уникальной.',
        );
      }

      seen.set(key, bug.id);
    }
  }
}

assertUniquePairs(bugs);
