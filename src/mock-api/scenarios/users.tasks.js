// Инвариант: задание не может ссылаться на несуществующий баг. Опечатка в id
// иначе давала бы задание, которое невозможно закрыть, — и понять это по UI
// было бы нельзя: галочка просто никогда не появляется. Полного покрытия
// каталога здесь не требуется: задания — методический слой, он вправе
// оставить часть багов на самостоятельный поиск.
function assertTasksReferKnownBugs(tasks, catalog) {
  for (const task of tasks) {
    for (const bugId of task.bugIds) {
      if (!catalog.some((bug) => bug.id === bugId)) {
        throw new Error(
          `Задание ${task.id} ссылается на баг ${bugId}, которого нет в каталоге.`,
        );
      }
    }
  }
}

assertTasksReferKnownBugs(usersTasks, bugs);
